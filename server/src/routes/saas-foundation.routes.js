const router = express.Router();
router.use((req, res, next) => {
  res.set('Cache-Control', 'no-store');
  if (!foundationAvailable()) return next(ApiError.notFound('Route not found'));
  if (['POST', 'PATCH'].includes(req.method) && !req.is('application/json')) {
    return next(new ApiError(415, 'Use application/json for bakery changes'));
  }
  next();
});
