const express = require('express');
const ApiError = require('../utils/ApiError');
const rateLimit = require('express-rate-limit');
const { resolveBakery, customerIntent, requireCustomer } = require('../saas/customer-access');
const security = require('../controllers/saas-customer-security.controller');
const auth = require('../controllers/saas-customer-auth.controller');
const reservations = require('../controllers/saas-reservation.controller');
const orders = require('../controllers/saas-customer-order.controller');
const router = express.Router({ mergeParams: true });
router.use((req, res, next) => ['GET', 'HEAD'].includes(req.method) ? next() : customerIntent(req, res, next));
router.use(resolveBakery);
const authLimit = rateLimit({ windowMs: 60000, limit: 10, standardHeaders: true, legacyHeaders: false, message: { success: false, message: 'Too many sign-in attempts. Try again shortly.' } });
const requestLimit = rateLimit({ windowMs: 15 * 60000, limit: 5, standardHeaders: true, legacyHeaders: false, message: { success: false, message: 'Too many account-mail requests. Try again later.' } });
const proofLimit = rateLimit({ windowMs: 60000, limit: 10, standardHeaders: true, legacyHeaders: false, message: { success: false, message: 'Too many account token attempts. Try again shortly.' } });
router.post('/password-reset/request', requestLimit, security.requestReset);
router.post('/password-reset/confirm', proofLimit, security.confirmReset);
router.post('/email-verification/confirm', proofLimit, security.confirmVerification);
router.post('/register', authLimit, auth.register);
router.post('/login', authLimit, auth.login);
router.post('/logout', auth.logout);
router.use(requireCustomer);
router.use((req, _res, next) => {
  if (req.path === '/me') return next();
  if (req.get('X-Saas-Customer-Id') !== String(req.customer._id)) return next(new ApiError(409, 'The customer session changed. Sign in again', { code: 'CUSTOMER_SESSION_CHANGED' }));
  next();
});
const orderLimit = rateLimit({ windowMs: 60000, limit: 30, keyGenerator: req => `${req.storeBakery._id}:${req.customer._id}`, standardHeaders: true, legacyHeaders: false, message: { success: false, message: 'Too many order attempts. Try again shortly.' } });
router.post('/email-verification/request', requestLimit, security.requestVerification);
router.post('/password/change', proofLimit, security.changePassword);
router.get('/me', auth.me);
router.post('/reservations/refresh', orderLimit, reservations.refreshCustomer);
router.post('/orders/:orderId/cancel', orderLimit, reservations.cancelCustomer);
router.post('/orders/quote', orderLimit, orders.quote);
router.post('/orders', orderLimit, orders.create);
router.get('/orders', orders.list);
router.get('/orders/:orderId', orders.get);
module.exports = router;
